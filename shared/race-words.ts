function poolFor(difficulty: RaceDifficulty): string[] {
  if (difficulty === "hard") return HARD_WORDS
  if (difficulty === "medium") return MEDIUM_WORDS
  return EASY_WORDS
}

/**
 * Generate `count` race words from the difficulty pool using Fisher-Yates
 * shuffling (cycling the pool when count exceeds its size). Pass `rng` for
 * deterministic tests; defaults to Math.random.
 */
export function generateRaceWords(
  count: number,
  difficulty: RaceDifficulty,
  rng: () => number = Math.random
): string[] {
  const pool = poolFor(difficulty)
  const words: string[] = []
  const shuffled = [...pool]
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(rng() * (i + 1))
    ;[shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]]
  }
  let idx = 0
  while (words.length < count) {
    if (idx >= shuffled.length) idx = 0
    words.push(shuffled[idx])
    idx++
  }
  return words
}
